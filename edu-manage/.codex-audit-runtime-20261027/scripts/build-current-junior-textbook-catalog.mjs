function insertUnitReflections(entries, volumeKey) {
  const unitTitles = unitsWithReflection[volumeKey]
  if (!unitTitles) return entries

  const result = []
  let index = 0
  let reflectionIndex = 0
  while (index < entries.length) {
    const start = index
    index += 1
    while (index < entries.length && entries[index].depth > 0) index += 1
    const group = entries.slice(start, index)
    result.push(...group)
    const unit = group[0]
    if (unit?.depth === 0 && unitTitles.includes(unit.title)) {
      reflectionIndex += 1
      result.push({
        id: `${volumeKey.replaceAll('|', '-')}-unit-reflection-${reflectionIndex}`,
        title: '单元思考与行动',
        depth: 1,
        path: [...unit.path, '单元思考与行动'],
      })
    }
  }
  return result
}

const volumes = source.volumes.map((volume) => {
  const preview = volume.sourceStatus === previewSourceStatus
  const publisher = editionPolicy.junior[volume.subject] ?? '按机构指定版本'
  const notes = (volume.directoryNotes ?? []).map(({ text }) => text)
  const references = [
    ...sourceReferences(volume.entries),
    ...(volumeSourceReferences[`${volume.subject}|${volume.title}`] ?? []),
  ]
  const publisherReferences = references.filter(({ url }) => {
    const host = new URL(url).hostname.toLowerCase()
    return host === 'www.pep.com.cn' || host === 'www.hbep.com'
  })
  const orderedReferences = publisherReferences.length
    ? [...publisherReferences, ...references.filter((reference) => !publisherReferences.includes(reference))]
    : references
  const entries = volume.entries
    .filter((entry) => !isSourceMetadata(entry))
    .map(({ id, title, depth, path }) => ({ id, title, depth, path }))
  const override = reviewedDirectoryOverrides[`${volume.subject}|${volume.title}`]
  const curatedEntries = override?.entries ?? entries.map((entry) => {
    if (volume.subject === '物理' && volume.title === '八年级上册' && entry.title === '绪言　开启科学探索之旅') {
      return { ...entry, title: '绪言 科学探索之旅', path: ['绪言 科学探索之旅'] }
    }
    return entry
  })
  const volumeKey = `${volume.subject}|${volume.title}`
  const corrections = reviewedTitleCorrections[volumeKey] ?? {}
  const correctedEntries = curatedEntries.map((entry) => ({
    ...entry,
    title: corrections[entry.title] ?? entry.title,
    path: entry.path.map((part) => corrections[part] ?? part),
  }))
  const reflectedEntries = insertUnitReflections(correctedEntries, volumeKey)
  const extraEntries = (supplementaryDirectoryEntries[volumeKey] ?? []).map((title, index) => ({
    id: `${volumeKey.replaceAll('|', '-')}-supplement-${index + 1}`,
    title,
    depth: 0,
    path: [title],
  }))
  const finalEntries = [...reflectedEntries, ...extraEntries]

  return {
    subject: volume.subject,
    title: volume.title,
    publisher,
    termLabel: termLabel(volume.title),
    directoryStatus: override?.directoryStatus ?? (preview
      ? 'PUBLIC_PREVIEW_AWAITING_PRINTED_BOOK_REVIEW'
      : volume.sourceStatus === 'USER_SUPPLIED_UNVERIFIED'
        ? 'USER_SUPPLIED_UNVERIFIED'
        : 'SOURCE_STATUS_UNSPECIFIED'),
    sourceReferences: orderedReferences,
    sourceNotes: notes,
    entries: finalEntries,
  }
})

