function termLabel(title) {
  if (title === '九年级全一册') return '2026 秋学年版'
  if (title.startsWith('七年级上册')) return '2024 秋学年版'
  if (title.startsWith('七年级下册')) return '2025 春学年版'
  if (title.startsWith('八年级上册')) return '2025 秋学年版'
  if (title.startsWith('八年级下册')) return '2026 春学年版'
  if (title.startsWith('九年级上册')) return '2026 秋学年版'
  if (title.startsWith('九年级下册')) return '2027 春学期预排'
  return '学年待核'
}

function isSourceMetadata(entry) {
  return /^(目录来源|目录旁证|版本来源|教材来源|来源链接)\s*[:：]/.test(entry.title.trim())
}

function sourceReferences(entries) {
  return entries.filter(isSourceMetadata).flatMap((entry) => {
    const match = entry.title.match(/^(目录来源|目录旁证|版本来源|教材来源|来源链接)\s*[:：]\s*(https?:\/\/[^\s)]+)/)
    return match ? [{ kind: match[1], url: match[2] }] : []
  })
}

function buildEntries(subject, title, rows) {
  let ancestors = []
  return rows.map((row, index) => {
    const path = [...ancestors.slice(0, row.depth), row.title]
    ancestors = path
    return {
      id: `${subject}-${title}-2024-directory-${index + 1}`,
      title: row.title,
      depth: row.depth,
      path,
    }
  })
}

