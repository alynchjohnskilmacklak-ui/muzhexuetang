function placeCorrectOption(question: QuestionSeed, targetIndex: number) {
  const answer = question.options[question.answerIndex]
  const distractors = question.options.filter((_, index) => index !== question.answerIndex)
  distractors.splice(targetIndex, 0, answer)
  return { options: distractors, answerIndex: targetIndex }
}

function makeSet(seed: TopicSeed): PracticeSet {
  const title = `${gradeTitles[seed.grade]}${seed.volume}`
  const volume = catalogVolumes.find((item) => item.subject === seed.subject && item.title === title)
  if (!volume) throw new Error(`Current textbook volume not found: ${seed.subject} ${title}`)

  const entry = volume.entries.find((item) => {
    const path = item.path?.length ? item.path : [item.title]
    return path.length === seed.path.length && path.every((part, index) => part === seed.path[index])
  })
  if (!entry) throw new Error(`Current textbook chapter not found: ${seed.subject} ${title} ${seed.path.join(' / ')}`)

  const path = entry.path?.length ? entry.path : [entry.title]
  const sourceReferences = volume.sourceReferences ?? []
  const directoryUrl = sourceReferences.find((source) => /^https?:\/\//.test(source.url))?.url
  const sourceNote = [
    `牧哲学堂原创拓展题，按${volume.publisher}${volume.termLabel ? `（${volume.termLabel}）` : ''}当前教材目录定位；题目与解析围绕本节概念、证据和常见错误编写。`,
    directoryUrl ? `教材目录交叉核对来源（目录证据性质以本地目录记录为准）：${directoryUrl}` : '',
    ...sourceReferences.slice(1, 3).map((source) => `补充目录来源：${source.url}`),
    ...(seed.extraDirectoryRefs ?? []).map((url) => `补充现行教材目录交叉核对（第三方）：${url}`),
    ...(seed.evidenceRefs ?? []).map((source) => `${source.label}：${source.url}`),
  ].filter(Boolean).join('；')
  const knowledgePoints = seed.points.map(([pointTitle, content], index) => ({
    id: `${seed.id}-kp${index + 1}`,
    title: pointTitle,
    content,
  }))

  return {
    id: seed.id,
    grade: seed.grade,
    subject: seed.subject,
    volume: seed.volume,
    chapter: path.slice(0, -1).join(' / ') || path[0],
    section: path.at(-1) ?? path[0],
    edition: [volume.publisher, volume.termLabel].filter(Boolean).join(' · '),
    sourceNote,
    catalogEvidence: directoryUrl ? {
      kind: sourceReferences[0]?.kind === 'publisher_url' ? 'publisher_url' : 'public_directory_url',
      ref: directoryUrl,
      locator: path.join(' / '),
    } : undefined,
    knowledgePoints,
    questions: seed.questions.map((question, index) => {
      const choices = placeCorrectOption(question, index)
      return {
        id: `${seed.id}-q${index + 1}`,
        type: 'single_choice',
        knowledgePointId: knowledgePoints[question.point].id,
        prompt: question.prompt,
        options: choices.options,
        answerIndex: choices.answerIndex,
        explanation: question.explanation,
        difficulty: index >= 2 ? '提升' : '基础',
        sourceRef: `${sourceNote}#${seed.id}-q${index + 1}`,
      }
    }),
  }
}

