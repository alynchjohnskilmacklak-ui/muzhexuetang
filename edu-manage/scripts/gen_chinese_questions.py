sections = []

def add(sid, grade, vol, chapter, sec_name, kp_id, kp_title, kp_content, questions):
    sections.append({
        'id': sid, 'grade': grade, 'subject': '语文', 'volume': vol,
        'chapter': chapter, 'section': sec_name,
        'knowledgePoints': [{'id': kp_id, 'title': kp_title, 'content': kp_content}],
        'questions': questions
    })

def q(qid, kpid, prompt, opts, ans, exp):
    """生成一道题"""
    diff = 'EASY' if qid.endswith(('q1','q2','q3')) else ('MEDIUM' if qid.endswith(('q4','q5','q6','q7')) else 'EXAM')
    return {'id': qid, 'knowledgePointId': kpid, 'prompt': prompt,
            'options': opts, 'answerIndex': ans, 'explanation': exp, 'difficulty': diff}

