// 不分年级、按学科合并去重（老班级数据用）
const FLAT: Record<string, string[]> = (() => {
  const m: Record<string, Set<string>> = {}
  for (const grade of Object.keys(GRADE_SUBJECT_KNOWLEDGE_POINTS)) {
    for (const subject of Object.keys(GRADE_SUBJECT_KNOWLEDGE_POINTS[grade])) {
      if (!m[subject]) m[subject] = new Set()
      GRADE_SUBJECT_KNOWLEDGE_POINTS[grade][subject].forEach((p) => m[subject].add(p))
    }
  }
  const out: Record<string, string[]> = {}
  for (const k of Object.keys(m)) out[k] = Array.from(m[k]).sort()
  return out
})()

export function getKnowledgePointOptions(subject?: string | null, grade?: string | null): string[] {
  if (!subject) return []
  if (grade && GRADE_SUBJECT_KNOWLEDGE_POINTS[grade]?.[subject]) {
    return GRADE_SUBJECT_KNOWLEDGE_POINTS[grade][subject]
  }
  return FLAT[subject] || []
}
