type Volume = '上' | '下'

const q4 = (
  volume: Volume,
  title: string,
  prompt: string,
  options: [string, string, string, string],
  answerIndex: number,
  explanation: string,
  sourceDetail = '',
): Partial<PracticeQuestion> => {
  const desiredAnswerIndex = [...title].reduce((sum, character) => sum + character.charCodeAt(0) ** 2, 0) % 4
  const revisedOptions = [...options]
  const [correctOption] = revisedOptions.splice(answerIndex, 1)
  revisedOptions.splice(desiredAnswerIndex, 0, correctOption)

  return {
    type: 'single_choice',
    prompt,
    options: revisedOptions,
    answerIndex: desiredAnswerIndex,
    explanation,
    difficulty: '提升',
    sourceRef: '依据人教统编版语文八年级' + volume + '册《' + title + '》课文内容原创改编；非中考真题。' + sourceDetail,
  }
}

