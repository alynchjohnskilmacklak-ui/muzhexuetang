import paramiko
cli = paramiko.SSHClient()
cli.set_missing_host_key_policy(paramiko.AutoAddPolicy())
cli.connect("101.200.191.201", username="root", password="Ren031213", timeout=25)
def run(cmd, t=60):
    _, o, e = cli.exec_command(cmd, timeout=t)
    return o.read().decode("utf-8","replace"), e.read().decode("utf-8","replace")
print("=== nginx: 首页相关 location / rewrite ===")
out,_ = run("grep -n -A4 'location = /\\|location / \\|rewrite\\|home.html\\|index ' /etc/nginx/sites-available/edu-manage.conf | head -80")
print(out)
print("=== 服务器上 home.html 有哪几份 ===")
out,_ = run("find /opt -name 'home.html' -printf '%p  %s bytes  %TY-%Tm-%Td %TH:%TM\\n' 2>/dev/null | head -20")
print(out)
print("=== 线上首页 title / h1 ===")
out,_ = run("curl -s http://127.0.0.1:3000/ | grep -o '<title>[^<]*</title>\\|<h1>[^<]*' | head -5")
print("  via :3000 ->", out.strip())
